  function bankQuestion(subject, diff, seed) {
    // seed = 天数：同一天固定同一题，不同天按公式轮转（配合四科轮换，保证每日题目不同）
    const pickOne = pool => seed == null
      ? pool[(Math.random() * pool.length) | 0]
      : pool[(seed * 7 + 3) % pool.length];
    if (diff === 'hard') {
      const pool = BANK[subject + '_hard'] || BANK.math_hard;
      return JSON.parse(JSON.stringify(pickOne(pool)));
    }
    if (diff === 'easy') {
      // 各科用自己的"简单"题库（此前固定抽 math_easy，导致每日一题千篇一律）
      const pool = BANK[subject + '_easy'] || BANK[subject] || BANK.math_easy;
      return JSON.parse(JSON.stringify(pickOne(pool)));
    }
    if (subject === 'final') return JSON.parse(JSON.stringify(pickOne((BANK.final || BANK.math).concat(BANK.final_hard))));
    const pool = BANK[subject] || BANK.math;
    return JSON.parse(JSON.stringify(pickOne(pool)));
  }

