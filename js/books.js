  const DB = {};
  LIST.forEach(b => { DB[b.id] = b; });
  function byWhere(place) { return LIST.filter(b => (b.where || []).indexOf(place) >= 0); }

  /* ==================== 阅读器 ==================== */
  const PER = 8;                                  // 每页 8 句
  let act = null;

  function flags() { return ADV.Game.flags; }
  function rec(id) {
    const f = flags();
    f.read = f.read || {};
    const r = f.read[id] || (f.read[id] = { marks: [], done: false, page: 0 });
    if (!r.marks) r.marks = [];
    return r;
  }
  function pageCount(bk) { return Math.max(1, Math.ceil(bk.lines.length / PER)); }
  function lineAt(a, i) { return a.book.lines[a.page * PER + i]; }

  function start(bookId, onDone) {
    if (act) return;
    const bk = DB[bookId];
    if (!bk) { if (onDone) onDone(false); return; }
    const r = rec(bookId);
    act = {
      id: bookId, book: bk, r,
      page: Math.min(r.page || 0, pageCount(bk) - 1),
      cur: 0, onDone, msg: '', t: 0
    };
  }
  function close() {
    const a = act; act = null;
    if (!a) return;
    a.r.page = a.page;
    const idx = pageIndexOfLine(a);
    ADV.Game.save();
    if (a.onDone) a.onDone({ book: a.book, marks: a.r.marks.length, page: a.page, pages: pageCount(a.book) });
  }
  function pageIndexOfLine(a) { return a.page * PER + a.cur; }

  function markLine() {
    const a = act;
    const idx = pageIndexOfLine(a);
    const L = a.book.lines[idx];
    if (!L) return;
    const f = flags();
    f.excerpts = f.excerpts || {};
    const key = a.id + '#' + idx;
    const at = a.r.marks.indexOf(idx);
    if (at < 0) {
      a.r.marks.push(idx);
      f.excerpts[key] = { day: ADV.Cal.day, from: a.book.name, text: L.t, note: L.n || '' };
      ADV.Audio.sfx('save');
      a.msg = '✍ 已抄进摘抄本';
    } else {
      a.r.marks.splice(at, 1);
      delete f.excerpts[key];
      ADV.Audio.sfx('cancel');
      a.msg = '（从摘抄本上擦掉了这一句）';
    }
  }

  function update(dt, press) {
    if (!act) return;
    const a = act; a.t += dt;
    const n = pageCount(a.book);
    const linesHere = Math.min(PER, a.book.lines.length - a.page * PER);
    if (press.up) { a.cur = (a.cur + linesHere - 1) % linesHere; ADV.Audio.sfx('cursor'); }
    if (press.down) { a.cur = (a.cur + 1) % linesHere; ADV.Audio.sfx('cursor'); }
    if (press.left && a.page > 0) { a.page--; a.cur = 0; ADV.Audio.sfx('cursor'); }
    if (press.right && a.page < n - 1) { a.page++; a.cur = 0; ADV.Audio.sfx('cursor'); }
    if (press.ok) markLine();
    if (press.cancel) {
      const lastPage = a.page >= n - 1;
      const readEnough = a.r.marks.length > 0 || lastPage;
      if (lastPage && !a.r.done) { a.r.done = true; }
      close();
      return readEnough;                      // 返回值仅供调试
    }
    return undefined;
  }

  function text(g, s, x, y, size, color, align) {
    g.font = FONT(size, 'bold'); g.textAlign = align || 'center'; g.textBaseline = 'top';
    g.fillStyle = 'rgba(0,0,0,.55)'; g.fillText(s, x + 2, y + 2);
    g.fillStyle = color; g.fillText(s, x, y);
  }

  function render(g) {
    if (!act) return;
    const a = act, bk = a.book, n = pageCount(bk);
    g.save();
    g.fillStyle = 'rgba(6,8,18,.88)'; g.fillRect(0, 0, W, H);
    const x = 80, y = 40, w = W - 160, h = H - 80;
    ADV.UI.drawWindow(g, x, y, w, h);
    // 书眉
    text(g, bk.name, W / 2, y + 16, 27, '#ffe9a8');
    text(g, bk.author + '　·　' + (CATNAME[bk.cat] || ''), W / 2, y + 52, 15, '#8ab4ff');
    text(g, `第 ${a.page + 1} / ${n} 页　·　✍ ${a.r.marks.length} / ${bk.lines.length} 句`, W / 2, y + 74, 14, '#8a94c0');
    // 正文
    const start = a.page * PER;
    for (let i = 0; i < PER; i++) {
      const L = bk.lines[start + i];
      if (!L) break;
      const ly = y + 104 + i * 33;
      const sel = i === a.cur, got = a.r.marks.indexOf(start + i) >= 0;
      if (sel) { g.fillStyle = 'rgba(120,150,255,.20)'; g.fillRect(x + 30, ly - 7, w - 60, 31); }
      text(g, (got ? '✍ ' : '') + L.t, x + 44, ly, 16, got ? '#ffd94c' : (sel ? '#ffffff' : '#c6cfe4'), 'left');
    }
    // 注释条：显示光标所在句的讲解
    const CL = lineAt(a, a.cur);
    if (CL) {
      const by = y + 104 + PER * 33 + 2;
      g.fillStyle = 'rgba(0,0,0,.30)'; g.fillRect(x + 30, by - 4, w - 60, 44);
      text(g, '【注】' + (CL.n || '——'), x + 44, by + 6, 14, '#9fe0b0', 'left');
    }
    if (a.msg) text(g, a.msg, W / 2, H - 76, 15, '#ffe9a8');
    text(g, '↑ ↓ 选句　← → 翻页　Z 摘抄 / 取消摘抄　X 合上书', W / 2, H - 44, 15, '#8a94c0');
    g.restore();
  }

  return {
    LIST, DB, CATS, byWhere, start, update, render,
    pageCount,
    get active() { return !!act; },
    get marks() { return act ? act.r.marks.length : 0; }
  };
